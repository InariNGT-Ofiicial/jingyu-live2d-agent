import assert from 'node:assert/strict';
import fs from 'node:fs';
import {MotionEngine,samplePoints,sampleMotion} from './web/engine.mjs';
const profile=JSON.parse(fs.readFileSync(new URL('./web/data/model-profile.json',import.meta.url)));
const values=new Map(profile.allParameters.map(p=>[p.id,p.default]));
const core={setParameterValueById:(id,v)=>values.set(id,v),getParameterValueById:id=>values.get(id)};
const events=[];
const engine=new MotionEngine(core,profile,(status)=>events.push(status));engine.idle=false;
const job={id:'test',compiled:{duration:2,steps:[{kind:'pose'}],tracks:[{id:'AngleX',action:0,start:0,duration:1.5,points:[[0,0],[.3,20],[1,20],[1.5,0]]}]}};
engine.start(job);for(let i=0;i<40;i++)engine.tick(16.667);
assert(values.get('AngleX')>19);
engine.paused=true;const elapsed=engine.elapsed;engine.tick(16.667);assert.equal(engine.elapsed,elapsed);
engine.paused=false;for(let i=0;i<160;i++)engine.tick(16.667);
assert.deepEqual(events,['playing','completed']);assert.equal(engine.job,null);assert(Math.abs(values.get('AngleX'))<.001);
engine.start(job);for(let i=0;i<40;i++)engine.tick(16.667);engine.stop();for(let i=0;i<60;i++)engine.tick(16.667);
assert(Math.abs(values.get('AngleX'))<.001);
engine.start(job);engine.tick(3000);assert.equal(engine.job,null);
assert.equal(samplePoints([[0,0],[1,1]],.5),.5);
assert.equal(sampleMotion([0,0,0,1,10],.5),5);
assert(Math.abs(sampleMotion([0,0,1,.1,0,.9,10,1,10],.5)-5)<.001);
console.log('Engine: pause, completion, stop recovery, easing and Bezier sampling passed.');
