import assert from 'node:assert/strict';
import fs from 'node:fs';
import {MotionEngine} from './web/engine.mjs';
const profile=JSON.parse(fs.readFileSync(new URL('./web/data/model-profile.json',import.meta.url)));
const values=new Map(profile.allParameters.map(p=>[p.id,p.default]));
const core={setParameterValueById:(id,v)=>values.set(id,v),getParameterValueById:id=>values.get(id)};
const engine=new MotionEngine(core,profile,()=>{});engine.idle=false;
engine.touchInput={zone:'chest',x:.5,y:.3};
for(let i=0;i<36;i++)engine.tick(16.667);
assert(values.get('ParamEyeBallY')<-.2,'brief initial shy glance');
for(let i=0;i<84;i++)engine.tick(16.667);
assert(values.get('key7')>.85,'sustained blush');
assert(Math.abs(values.get('ParamEyeBallY'))<.03,'gaze returns instead of remaining averted');
assert(values.get('ParamMouthForm')>.28,'gentle smile while held');
assert(values.get('PositionX')>9,'torso still follows drag');
engine.touchInput=null;engine.tick(16.667);
assert(values.get('key7')>.7,'release fades instead of snapping');
for(let i=0;i<240;i++)engine.tick(16.667);
assert(values.get('key7')<.01,'blush returns to neutral');
assert(Math.abs(values.get('PositionX'))<.01);
console.log('Hold emotion: sustained blush, gaze, torso follow, smooth release passed');
