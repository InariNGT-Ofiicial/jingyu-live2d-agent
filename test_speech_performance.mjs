import assert from 'node:assert/strict';
import fs from 'node:fs';
import {speechPose,speechEmotion} from './web/speech-performance.mjs';
import {MotionEngine} from './web/engine.mjs';
const styles=JSON.parse(fs.readFileSync('web/data/speech-styles.json'));
assert.equal(speechEmotion('欢迎你！'),'happy');assert.equal(speechEmotion('为什么呢？'),'curious');
const a=speechPose(styles,{text:'欢迎',time:1});
assert(a.values.ParamMouthForm>0);assert.equal(a.emotion,'happy');
assert.deepEqual(a,speechPose(styles,{text:'欢迎',time:1}),'same audio clock gives same pose');
assert.equal(speechPose(styles,{text:'欢迎',time:2,performance:{motion:false}}),null);
assert.equal(speechPose(styles,{text:'欢迎',time:2,duration:2}).values.AngleX,0);
const profile=JSON.parse(fs.readFileSync('web/data/model-profile.json')),values=new Map();
const core={setParameterValueById:(id,v)=>values.set(id,v),getParameterValueById:id=>values.get(id)||0};
const engine=new MotionEngine(core,profile,()=>{});engine.idle=false;engine.speechReserved=true;engine.speechPose=a;
engine.touchInput={zone:'chest',x:1,y:1};engine.tick(1000);
assert.equal(engine.touchInput,null,'speech takes ownership from a held pointer');
assert(values.get('ParamMouthForm')>.4);
engine.start({id:'explicit',compiled:{duration:2,steps:[{kind:'pose'}],tracks:[{id:'AngleX',action:0,start:0,duration:2,points:[[0,20],[2,20]]}]}});
engine.tick(1000);assert(values.get('AngleX')>19,'explicit motion takes priority over speech');
engine.stop();engine.speechPose=null;engine.speechReserved=false;engine.tick(1000);
assert(Math.abs(values.get('ParamMouthForm'))<.01,'stop returns to neutral');
console.log('Speech: semantic styles, audio clock, opt-out, priority, interruption and neutral recovery passed');
