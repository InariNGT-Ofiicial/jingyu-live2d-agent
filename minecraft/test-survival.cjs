const assert=require('node:assert/strict');
const {decide,observe}=require('./survival-policy.cjs');
const {Vec3}=require('vec3');
const sensor={entity:{position:new Vec3(0,64,0),metadata:{1:300}},inventory:{items:()=>[]},entities:{},blockAt:()=>({name:'air'}),time:{timeOfDay:6000},health:20,food:20,oxygenLevel:2};
assert.equal(observe(sensor,{}).oxygen,20,'Other entity oxygen must not affect the player');
sensor.entity.metadata[1]=60;assert.equal(observe(sensor,{}).oxygen,4);
const base={health:20,food:20,oxygen:20,inventory:{},night:false,animals:[],shelter:null,danger:null};
const policy=(patch={},memory={},goal)=>decide({...base,...patch},memory,goal);
assert.equal(policy().skill,'gather');
assert.equal(policy({inventory:{oak_log:1}}).args.item,'planks');
assert.equal(policy({inventory:{oak_planks:4}}).args.item,'crafting_table');
assert.equal(policy({inventory:{crafting_table:1}}).skill,'station');
assert.equal(policy({inventory:{oak_planks:3,stick:2}},{table:{x:0,y:64,z:0}}).args.item,'wooden_pickaxe');
assert.equal(policy({inventory:{wooden_pickaxe:1}},{table:{}}).args.resource,'stone');
assert.equal(policy({food:10,inventory:{apple:1}}).skill,'eat');
assert.equal(policy({food:3,animals:[{id:2}]}).skill,'hunt');
assert.equal(policy({food:3}).skill,'explore');
assert.equal(policy({danger:{id:3,name:'creeper',distance:3},inventory:{apple:1},food:10}).skill,'retreat');
assert.equal(policy({oxygen:4}).skill,'escape');
assert.equal(policy({health:0}).skill,'halt');
assert.equal(policy({night:true,shelter:{closed:false,distance:10}}).skill,'shelter');
assert.equal(policy({night:true,shelter:{closed:true,distance:0}}).skill,'wait');
assert.equal(policy({shelter:{closed:true,distance:0}}).skill,'exit');
assert.equal(policy({}, {}, 'return-home').skill,'halt');
const inv={stone_pickaxe:1,stone_axe:1,apple:4};
const memory={table:{},furnace:{},home:{}};
assert.equal(policy({inventory:inv},memory).skill,'complete');
assert.equal(policy({inventory:{...inv,oak_planks:10}},memory,'sustain').skill,'wait');
assert.equal(policy({inventory:{stone_pickaxe:1,stone_axe:1,oak_log:1,oak_planks:2}},{table:{},furnace:{}}).skill,'smelt');
console.log('Survival policy: dependency resolution, emergency priority, food, night, objectives passed');
